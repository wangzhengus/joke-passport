size_t app_jokes_count(void)
{
    return sizeof(s_jokes) / sizeof(s_jokes[0]);
}

const app_joke_t *app_jokes_get(size_t index)
{
    size_t n = app_jokes_count();
    if (n == 0) {
        return NULL;
    }
    return &s_jokes[index % n];
}
